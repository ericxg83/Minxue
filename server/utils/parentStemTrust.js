/**
 * 「多小问大题公共题干疑似丢失」判据（2026-09-20 第19题事故）。
 *
 * ── 事故 ────────────────────────────────────────────────────────────────
 * 任务 5636fc30「第19章实数复习1」第19题，原卷：
 *   「如图，一只蚂蚁从点A沿数轴向右爬行了2个单位长度到达点B，点A表示-√2，
 *     设点B所表示的实数为m」+ 数轴图
 *   (1)实数m的值是____；(2)化简：|m+1|+|m-1|=____；
 *   (3)若在数轴上有C,D两点分别表示实数c,d，且|3c+d|与√(d+9)互为相反数，求cd的立方根。
 * 落库结果：parent_stem = NULL，content 只剩 (1)(2)(3)。
 *   → 答案引擎判「题干缺少条件」→ answer 留空 → 界面显示「AI 未判定·缺少参考答案」。
 * 同任务 p3/p4 两页的 6 道多小问大题（题19~24）全部中招；另在任务 165acb27 第24题复现。
 *
 * 成因：弱视觉模型倾向把多小问大题【合并成一条 content】输出，同时把公共题干整段丢掉。
 *   OCR prompt 对「合并」路径的公共条件约束是软约束（要求写进 content），弱模型必然踩坑，
 *   而写入侧原先没有任何校验能发现这种「内容型丢失」。
 *
 * ── 判据 ────────────────────────────────────────────────────────────────
 *   content 去掉首尾空白后【以 (1)/(（1） 开头】，且文中还含 (2)/(3) 标号，
 *   而 parent_stem 为空 → 公共条件既不在 content、也不在 parent_stem，必然已丢失。
 *
 * ✅ 不误伤「公共条件已写在 content 里」的合并题（如「已知正数m的两个平方根分别是a和b。
 *    (1)…(2)…」）—— 它们不以 (1) 开头。
 * ✅ 不误伤普通单问题。
 *
 * ⚠️ 已知假阳性（2026-09-20 全库实测 14 命中 / 7 真 7 假）：确实存在本来就没有公共题干的
 *   多小问，如「(1)一个正方形的周长是16cm，…？(2)一个正方形的面积是16cm²，…？」、
 *   「化简：(1)√(8-2√15). (2)√(2-√3).」。故本判据**只用于告警，不得用于拦截落库**。
 *
 * 判据唯一实现，写入侧（worker.js recognizeQuestions）与任何读取侧/审计脚本都必须 import 本文件，
 * 禁止另写一份正则。
 */

/**
 * @param {string|null|undefined} content    本问 content
 * @param {string|null|undefined} parentStem 公共题干
 * @returns {boolean} true = 疑似公共题干丢失
 */
export const looksLikeLostParentStem = (content, parentStem) => {
  if (parentStem && String(parentStem).trim()) return false
  const s = String(content || '').trim()
  if (!/^[（(]\s*1\s*[)）]/.test(s)) return false
  return /[（(]\s*[23]\s*[)）]/.test(s)
}
